// Generates theme overrides from the vendored awesome-claude-design reference files.
// Maps each reference palette onto this project's token names. No dependencies.
// Usage: node scripts/make-themes.mjs   -> src/themes/generated.css, dist/themes.css, src/themes/REPORT.md
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = "design-reference/awesome-claude-design/design-md";
const pick = (vars, names) => names.map(n => vars[n]).find(Boolean);

const hex = v => /^#[0-9a-f]{6}$/i.test(v ?? "") ? v.toLowerCase() : null;
const lum = h => { const c = [1,3,5].map(i => parseInt(h.slice(i,i+2),16)/255).map(v => v<=.03928 ? v/12.92 : ((v+.055)/1.055)**2.4); return .2126*c[0]+.7152*c[1]+.0722*c[2]; };
const ratio = (a,b) => { const [x,y] = [lum(a),lum(b)].sort((p,q)=>q-p); return (x+.05)/(y+.05); };
const shade = (h, f) => "#" + [1,3,5].map(i => Math.max(0, Math.min(255, Math.round(parseInt(h.slice(i,i+2),16)*f))).toString(16).padStart(2,"0")).join("");

const themes = [];
for (const family of readdirSync(ROOT)) {
  for (const file of readdirSync(join(ROOT, family)).filter(f => f.endsWith(".md"))) {
    const md = readFileSync(join(ROOT, family, file), "utf8");
    const section = md.split(/^## 2\./m)[1] ?? "";
    const block = section.match(/```[^\n]*\n([\s\S]*?)```/)?.[1] ?? "";
    // Light-mode variables only: skip variables named *-dark, keep the rest.
    const vars = {};
    for (const m of block.matchAll(/^\s*--([\w-]+):\s*([^\s/][^/\n]*?)\s*(?:\/\*.*)?$/gm)) if (!m[1].endsWith("-dark")) vars[m[1]] = m[2].trim();

    const canvas = hex(pick(vars, ["bg", "bg-primary", "canvas", "background"]));
    const ink = hex(pick(vars, ["text", "text-primary", "ink", "fg"]));
    const primary = hex(pick(vars, ["accent", "primary", "brand", "system-blue"]));
    if (!canvas || !ink || !primary) { themes.push({ id: `${family}-${file.slice(0,-3)}`, skipped: "palette not mappable" }); continue; }

    const id = `${family}-${file.slice(0,-3)}`;
    const surface = hex(pick(vars, ["surface", "bg-elevated", "bg-alt", "bg-secondary", "surface-grouped"])) ?? canvas;
    const t = {
      primary,
      "primary-hover": hex(pick(vars, ["accent-hover", "primary-hover"])) ?? shade(primary, .88),
      "primary-active": shade(hex(pick(vars, ["accent-hover", "primary-hover"])) ?? primary, .78),
      "on-primary": ratio("#ffffff", primary) >= ratio("#000000", primary) ? "#ffffff" : "#000000",
      ink, body: hex(pick(vars, ["text-secondary", "body"])) ?? ink,
      muted: hex(pick(vars, ["text-muted", "muted"])) ?? pick(vars, ["text-muted"]) ?? "#6b6b76",
      canvas, surface,
      "surface-sunken": hex(pick(vars, ["surface-2", "bg-alt", "bg-secondary", "surface-grouped"])) ?? surface,
      hairline: pick(vars, ["border", "separator", "hairline"]) ?? shade(canvas, .9),
      danger: hex(pick(vars, ["danger", "system-red", "error"])) ?? "#c0392b",
      success: hex(pick(vars, ["success", "system-green"])) ?? "#2e7d4f",
      warning: hex(pick(vars, ["warning", "system-orange", "accent-warm"])) ?? "#b7791f",
    };
    t["on-danger"] = ratio("#ffffff", t.danger) >= ratio("#000000", t.danger) ? "#ffffff" : "#000000";
    themes.push({
      id, family, tokens: t,
      cPrimary: ratio(t["on-primary"], primary), cInk: ratio(ink, canvas), cDanger: ratio(t["on-danger"], t.danger),
    });
  }
}

const ok = themes.filter(t => t.tokens);
const css = ok.map(t =>
  `[data-theme="${t.id}"] {\n` + Object.entries(t.tokens).map(([k, v]) => `  --color-${k}: ${v};`).join("\n") +
  `\n  background: var(--color-canvas);\n  color: var(--color-body);\n}\n`).join("\n");
const banner = "/* Generated by scripts/make-themes.mjs from design-reference/awesome-claude-design. Do not edit. */\n";
mkdirSync("src/themes", { recursive: true }); mkdirSync("dist", { recursive: true });
writeFileSync("src/themes/generated.css", banner + css); writeFileSync("dist/themes.css", banner + css);

const row = t => `| ${t.id} | ${t.cPrimary.toFixed(2)} ${t.cPrimary >= 4.5 ? "pass" : "FAIL"} | ${t.cInk.toFixed(2)} ${t.cInk >= 4.5 ? "pass" : "FAIL"} | ${t.cDanger.toFixed(2)} ${t.cDanger >= 4.5 ? "pass" : "FAIL"} |`;
const report = `# Generated themes\n\n${ok.length} themes generated, ${themes.length - ok.length} skipped (${themes.filter(t=>t.skipped).map(t=>t.id).join(", ") || "none"}).\nColors only: fonts, radii and spacing stay on this project's tokens. WCAG AA needs 4.5.\n\n| Theme | on-primary / primary | ink / canvas | on-danger / danger |\n|---|---|---|---|\n${ok.map(row).join("\n")}\n`;
writeFileSync("src/themes/REPORT.md", report);
writeFileSync("src/themes/ids.js", "// Generated by scripts/make-themes.mjs\nexport const THEME_IDS = " + JSON.stringify(ok.map(t => t.id), null, 2) + ";\n");
console.log(`${ok.length} generated, ${themes.length - ok.length} skipped`);
console.log("AA failures (on-primary):", ok.filter(t => t.cPrimary < 4.5).map(t => t.id).join(", ") || "none");
